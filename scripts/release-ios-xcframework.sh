#!/bin/bash

# # prepare
# $ rustup target add aarch64-apple-ios
# $ rustup target add aarch64-apple-ios-sim
# $ rustup target add x86_64-apple-ios

set -e

BASEDIR=$(dirname $0)
BASEDIR=$(cd $BASEDIR && pwd -P)
ROOTDIR=${BASEDIR}/..
ROOTDIR=$(cd $ROOTDIR && pwd -P)

BUILD_MODE="release"
CARGO_FLAGS="--release --config profile.release.lto=false"
if [ "$1" = "debug" ]; then
    BUILD_MODE="debug"
    CARGO_FLAGS=""
fi

pushd ${ROOTDIR} > /dev/null

# Deployment target: keep the cdylib's LC_BUILD_VERSION minos in lockstep with the
# framework Info.plist MinimumOSVersion written below — App Store validation rejects
# an embedded framework whose two minimum-OS values disagree. rustc honours this env
# for the apple targets, so both the static and dynamic builds inherit it.
export IPHONEOS_DEPLOYMENT_TARGET="${IPHONEOS_DEPLOYMENT_TARGET:-13.0}"

# Marketing/build version for the framework Info.plist. Strip any -prerelease suffix
# (e.g. 7.0.0-alpha01 -> 7.0.0): App Store rejects a non-numeric CFBundleShortVersionString.
WORKSPACE_VERSION=$(sed -n 's/^version = "\(.*\)"/\1/p' Cargo.toml | head -1)
SHORT_VERSION="${WORKSPACE_VERSION%%-*}"
BUNDLE_ID="jp.co.cri-mw.optpix.ssruntime"

# Build ssruntime for the three Apple-mobile targets. Each build emits both
# libssruntime.a (staticlib) and libssruntime.dylib (cdylib).
#   aarch64-apple-ios      -> device
#   aarch64-apple-ios-sim  -> Apple Silicon simulator
#   x86_64-apple-ios       -> Intel simulator
FEATURES="libc_alloc,panic-handler"
cargo build --target aarch64-apple-ios     -p ssruntime --features ${FEATURES} ${CARGO_FLAGS}
cargo build --target aarch64-apple-ios-sim -p ssruntime --features ${FEATURES} ${CARGO_FLAGS}
cargo build --target x86_64-apple-ios      -p ssruntime --features ${FEATURES} ${CARGO_FLAGS}

# The C-API header is generated by libs/ssruntime/build.rs (cbindgen) during the
# builds above; it is platform-agnostic, so reuse it for every xcframework slice.
WORK=target/xcframework
HDR_DIR=${WORK}/headers
STAGE=${WORK}/staging
OUT_STATIC=${WORK}/static
OUT_DYNAMIC=${WORK}/dynamic

# xcodebuild -create-xcframework refuses to overwrite an existing output bundle.
/bin/rm -rf ${OUT_STATIC} ${OUT_DYNAMIC} ${STAGE}
/bin/mkdir -p ${HDR_DIR} ${STAGE}/sim-static ${STAGE}/sim-dynamic ${STAGE}/device-dynamic
cp libs/ssruntime/target/ssruntime.h ${HDR_DIR}/

D=${BUILD_MODE}

# --- static xcframework: device (arm64) + simulator (arm64 + x86_64) ---
# Device is a single arch; the two simulator archs are fused into one fat slice.
# arm64 device and arm64 simulator cannot coexist in a fat binary (same arch) —
# the xcframework keeps them apart via platform-variant metadata instead.
lipo -create \
    target/aarch64-apple-ios-sim/${D}/libssruntime.a \
    target/x86_64-apple-ios/${D}/libssruntime.a \
    -output ${STAGE}/sim-static/libssruntime.a

xcodebuild -create-xcframework \
    -library target/aarch64-apple-ios/${D}/libssruntime.a -headers ${HDR_DIR} \
    -library ${STAGE}/sim-static/libssruntime.a           -headers ${HDR_DIR} \
    -output ${OUT_STATIC}/libssruntime.xcframework

# --- dynamic xcframework (.framework-wrapped slices) ---
# App Store embedding requires a dynamic library to ship as a .framework bundle
# (Info.plist + bundle layout), not a bare dylib. Wrap each slice as an iOS *flat*
# framework: the binary, Headers/, Modules/ and Info.plist all sit at the bundle
# root (no macOS-style Versions/ symlink tree). Rust stamps the cdylib's
# LC_ID_DYLIB with a build-machine path; the install_name is rewritten to the
# rpath-relative path dyld expects for an embedded framework.
make_ios_framework() {
    # $1 = staging dir to build the .framework in
    # $2 = input dylib (already lipo'd for its platform)
    # $3 = CFBundleSupportedPlatforms value (iPhoneOS | iPhoneSimulator)
    local dir="$1" dylib="$2" platform="$3"
    local fw="${dir}/libssruntime.framework"
    /bin/rm -rf "${fw}"
    /bin/mkdir -p "${fw}/Headers" "${fw}/Modules"

    cp "${dylib}" "${fw}/libssruntime"
    install_name_tool -id @rpath/libssruntime.framework/libssruntime "${fw}/libssruntime"
    cp "${HDR_DIR}/ssruntime.h" "${fw}/Headers/ssruntime.h"

    cat > "${fw}/Modules/module.modulemap" <<EOF
framework module libssruntime {
    umbrella header "ssruntime.h"
    export *
    module * { export * }
}
EOF

    cat > "${fw}/Info.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>CFBundleDevelopmentRegion</key><string>en</string>
	<key>CFBundleExecutable</key><string>libssruntime</string>
	<key>CFBundleIdentifier</key><string>${BUNDLE_ID}</string>
	<key>CFBundleInfoDictionaryVersion</key><string>6.0</string>
	<key>CFBundleName</key><string>libssruntime</string>
	<key>CFBundlePackageType</key><string>FMWK</string>
	<key>CFBundleShortVersionString</key><string>${SHORT_VERSION}</string>
	<key>CFBundleVersion</key><string>${SHORT_VERSION}</string>
	<key>MinimumOSVersion</key><string>${IPHONEOS_DEPLOYMENT_TARGET}</string>
	<key>CFBundleSupportedPlatforms</key><array><string>${platform}</string></array>
	<key>UIDeviceFamily</key><array><integer>1</integer><integer>2</integer></array>
</dict>
</plist>
EOF
    # Catch a malformed plist here rather than at App Store validation time.
    plutil -lint "${fw}/Info.plist" > /dev/null
}

# Device is a single arch; the two simulator archs fuse into one fat binary (their
# IOSSIMULATOR platform in LC_BUILD_VERSION keeps them distinct from the device slice).
cp target/aarch64-apple-ios/${D}/libssruntime.dylib ${STAGE}/device-dynamic/libssruntime.dylib
make_ios_framework ${STAGE}/device-dynamic ${STAGE}/device-dynamic/libssruntime.dylib iPhoneOS

lipo -create \
    target/aarch64-apple-ios-sim/${D}/libssruntime.dylib \
    target/x86_64-apple-ios/${D}/libssruntime.dylib \
    -output ${STAGE}/sim-dynamic/libssruntime.dylib
make_ios_framework ${STAGE}/sim-dynamic ${STAGE}/sim-dynamic/libssruntime.dylib iPhoneSimulator

xcodebuild -create-xcframework \
    -framework ${STAGE}/device-dynamic/libssruntime.framework \
    -framework ${STAGE}/sim-dynamic/libssruntime.framework \
    -output ${OUT_DYNAMIC}/libssruntime.xcframework

# --- Code signing (opt-in via env) ------------------------------------------
# Sign the xcframeworks for distribution authenticity when APPLE_SIGNING_IDENTITY
# is set (maps to the SS_APPLE_SIGNING_IDENTITY secret; see
# .github/workflows/release.yml). iOS code is NOT notarized and does NOT use the
# macOS hardened runtime — the consuming app re-signs the embedded framework with
# its own identity at its build time; this signature only lets consumers verify
# the package's provenance (Xcode 15+ "verify app dependencies with signatures").
#
# The static xcframework wraps bare `.a` archives, which are NOT themselves
# code-signable; signing seals the *bundle* so consumers can still verify the
# static package's provenance. The dynamic one is signed inside-out: each
# embedded .framework first, then the xcframework wrapper.
if [ -n "${APPLE_SIGNING_IDENTITY:-}" ]; then
    echo "==> Codesigning iOS xcframeworks as: ${APPLE_SIGNING_IDENTITY}"

    # dynamic: sign embedded frameworks, then the wrapper.
    for fw in "${OUT_DYNAMIC}"/libssruntime.xcframework/*/libssruntime.framework; do
        codesign --force --sign "${APPLE_SIGNING_IDENTITY}" --timestamp "${fw}"
        codesign --verify --strict --verbose=2 "${fw}"
    done
    codesign --force --sign "${APPLE_SIGNING_IDENTITY}" --timestamp \
        "${OUT_DYNAMIC}/libssruntime.xcframework"
    codesign --verify --strict --verbose=2 "${OUT_DYNAMIC}/libssruntime.xcframework"

    # static: seal the bundle (its `.a` members are not individually signable).
    codesign --force --sign "${APPLE_SIGNING_IDENTITY}" --timestamp \
        "${OUT_STATIC}/libssruntime.xcframework"
    codesign --verify --strict --verbose=2 "${OUT_STATIC}/libssruntime.xcframework"
else
    echo "==> Skipping iOS codesign (APPLE_SIGNING_IDENTITY not set)"
fi

popd > /dev/null
