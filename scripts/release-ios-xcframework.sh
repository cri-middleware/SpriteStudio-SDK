#!/bin/bash

# # prepare
# $ rustup target add aarch64-apple-ios
# $ rustup target add aarch64-apple-ios-sim
# $ rustup target add x86_64-apple-ios

set -e

BASEDIR=$(dirname $0)
BASEDIR=$(cd $BASEDIR && pwd -P)
ROOTDIR=${BASEDIR}/..
ROOTDIR=$(cd $ROOTDIR && pwd -P)

BUILD_MODE="release"
CARGO_FLAGS="--release --config profile.release.lto=false"
if [ "$1" = "debug" ]; then
    BUILD_MODE="debug"
    CARGO_FLAGS=""
fi

pushd ${ROOTDIR} > /dev/null

# Build ssruntime for the three Apple-mobile targets. Each build emits both
# libssruntime.a (staticlib) and libssruntime.dylib (cdylib).
#   aarch64-apple-ios      -> device
#   aarch64-apple-ios-sim  -> Apple Silicon simulator
#   x86_64-apple-ios       -> Intel simulator
FEATURES="libc_alloc,panic-handler"
cargo build --target aarch64-apple-ios     -p ssruntime --features ${FEATURES} ${CARGO_FLAGS}
cargo build --target aarch64-apple-ios-sim -p ssruntime --features ${FEATURES} ${CARGO_FLAGS}
cargo build --target x86_64-apple-ios      -p ssruntime --features ${FEATURES} ${CARGO_FLAGS}

# The C-API header is generated by libs/ssruntime/build.rs (cbindgen) during the
# builds above; it is platform-agnostic, so reuse it for every xcframework slice.
WORK=target/xcframework
HDR_DIR=${WORK}/headers
STAGE=${WORK}/staging
OUT_STATIC=${WORK}/static
OUT_DYNAMIC=${WORK}/dynamic

# xcodebuild -create-xcframework refuses to overwrite an existing output bundle.
/bin/rm -rf ${OUT_STATIC} ${OUT_DYNAMIC} ${STAGE}
/bin/mkdir -p ${HDR_DIR} ${STAGE}/sim-static ${STAGE}/sim-dynamic ${STAGE}/device-dynamic
cp libs/ssruntime/target/ssruntime.h ${HDR_DIR}/

D=${BUILD_MODE}

# --- static xcframework: device (arm64) + simulator (arm64 + x86_64) ---
# Device is a single arch; the two simulator archs are fused into one fat slice.
# arm64 device and arm64 simulator cannot coexist in a fat binary (same arch) —
# the xcframework keeps them apart via platform-variant metadata instead.
lipo -create \
    target/aarch64-apple-ios-sim/${D}/libssruntime.a \
    target/x86_64-apple-ios/${D}/libssruntime.a \
    -output ${STAGE}/sim-static/libssruntime.a

xcodebuild -create-xcframework \
    -library target/aarch64-apple-ios/${D}/libssruntime.a -headers ${HDR_DIR} \
    -library ${STAGE}/sim-static/libssruntime.a           -headers ${HDR_DIR} \
    -output ${OUT_STATIC}/libssruntime.xcframework

# --- dynamic xcframework (bare dylib) ---
# Rust stamps the cdylib's LC_ID_DYLIB with a build-machine path; rewrite it to
# @rpath so the dylib is embeddable/loadable from a consuming app bundle.
cp target/aarch64-apple-ios/${D}/libssruntime.dylib ${STAGE}/device-dynamic/libssruntime.dylib
install_name_tool -id @rpath/libssruntime.dylib ${STAGE}/device-dynamic/libssruntime.dylib

lipo -create \
    target/aarch64-apple-ios-sim/${D}/libssruntime.dylib \
    target/x86_64-apple-ios/${D}/libssruntime.dylib \
    -output ${STAGE}/sim-dynamic/libssruntime.dylib
install_name_tool -id @rpath/libssruntime.dylib ${STAGE}/sim-dynamic/libssruntime.dylib

xcodebuild -create-xcframework \
    -library ${STAGE}/device-dynamic/libssruntime.dylib -headers ${HDR_DIR} \
    -library ${STAGE}/sim-dynamic/libssruntime.dylib     -headers ${HDR_DIR} \
    -output ${OUT_DYNAMIC}/libssruntime.xcframework

popd > /dev/null
