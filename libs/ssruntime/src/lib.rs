//! The playback **Brain** of the SpriteStudio SDK.
//!
//! `ssruntime` loads `.ssab` animation binaries produced by `ssconverter` and computes,
//! for every frame, everything a renderer needs: part transforms, mesh deformations,
//! colors, and a cross-engine **DrawBatch** plan. It performs no rendering of its own —
//! each *Player* (engine integration) consumes the emitted state and draws with its
//! native API. That split is what keeps playback identical across engines.
//!
//! ```text
//!   .sspj (XML)          .ssab (FlatBuffers)        FrameData + DrawBatch         pixels
//!        │                       │                          │                       │
//!        └──── ssconverter ──────┴──────  ssruntime  ────────┴────── Player ─────────┘
//!                                          (Brain)                    (Body)
//! ```
//!
//! # API faces
//!
//! The same core is exposed three ways; pick the one that matches your host:
//!
//! | Face | Entry point | Consumer |
//! |---|---|---|
//! | Rust (`rlib`) | [`Context`], [`AnimationResource`] | Rust-native Players, this crate's own tests |
//! | C ABI (`staticlib` / `cdylib`, emitted by `ssruntime-ffi`) | [`ffi`] — `ss_runtime_*`, header generated by `cbindgen` | Unity, Godot, Ren'Py, Flutter, C/C++ engines |
//! | JS / WASM (emitted by `ssruntime-ffi`) | the `web` module (feature `web`, `wasm-bindgen`) | the browser Player collection |
//!
//! # Quick start (Rust)
//!
//! ```no_run
//! use ssruntime::{AnimationResource, Context};
//!
//! # fn main() -> Result<(), ssruntime::error::SSRuntimeError> {
//! # let ssab_bytes: &[u8] = &[];
//! // 1. Parse the .ssab once. A resource is read-only and can back many contexts.
//! // SAFETY: a pack the converter wrote, so a valid .ssab (see Limitations below).
//! let resource = unsafe { AnimationResource::new(ssab_bytes) }?;
//!
//! // 2. A context holds the playback state of one animation instance.
//! let mut ctx = Context::new();
//! ctx.bind_resource(&resource);
//! ctx.setup_animation("Wait")?;
//! ctx.set_loop_count(-1); // -1 = loop forever
//! ctx.play();
//!
//! // 3. Each tick: advance time, then ask for that frame's data.
//! //    `update` takes **milliseconds**, matching the animation's fps.
//! while ctx.is_playing() {
//!     let frame_no = ctx.update(1000.0 / 60.0);
//!     let framedata: &[u8] = ctx.get_frame_data(frame_no)?;
//!     // `framedata` is a FlatBuffer — see SCHEMA.md for how to read it.
//! }
//! # Ok(())
//! # }
//! ```
//!
//! Transport, loop count, ping-pong, playback range and FPS all live on the context and
//! are backed by [`core::playback_controller::PlaybackController`].
//!
//! Frame numbers are `f32`: the runtime interpolates between source keyframes, so
//! playback stays smooth above and below the authored framerate.
//!
//! # Module map
//!
//! - [`core`] — the evaluation core: interpolation, matrices, geometry,
//!   [`core::playback_controller`] (transport, loop, ping-pong, seek),
//!   [`core::framedata`] (the per-frame FlatBuffer), [`core::override_layer`]
//!   (per-part color / cell / visibility overrides), [`core::effect`] (particles).
//! - [`types`] — `#[repr(C)]` POD structs returned by value across API boundaries.
//! - [`error`] — [`error::SSRuntimeError`] and its stable integer codes.
//! - [`ffi`] — the C ABI surface (feature `ffi`).
//! - `web` — the `wasm-bindgen` surface (feature `web`).
//!
//! # Feature flags
//!
//! | Feature | Purpose |
//! |---|---|
//! | `ffi` | C-API exports. For `ssruntime-ffi`, not for Rust dependents — see below. |
//! | `libc_alloc` | `libc::malloc`/`free`-backed `#[global_allocator]` for `no_std` FFI builds (mobile / desktop). |
//! | `wasm_alloc` | `dlmalloc`-backed `#[global_allocator]` for `no_std` WASM builds. |
//! | `emscripten_alloc` | Emscripten libc-backed `#[global_allocator]` for Emscripten `no_std` builds. |
//! | `custom_alloc` | Routes allocation and abort to host-provided `ss_custom_alloc` / `ss_custom_free` / `ss_custom_abort` symbols, for console and engine allocators. Build as `staticlib`. |
//! | `panic-handler` | Provides `#[panic_handler]` for `no_std` FFI builds. |
//! | `web` | `wasm-bindgen` bindings for JS/TS interop. Same caveat as `ffi`. |
//! | `std` | Opt-in developer ergonomics only; never used by release scripts. |
//!
//! Nothing is on by default: a Rust dependent wants the `rlib` and nothing else.
//!
//! `ffi` and `web` exist for `ssruntime-ffi`, the sibling crate that emits this one as
//! a `staticlib` / `cdylib`. Enabling either from a Rust dependency compiles
//! `#[no_mangle] extern "C"` symbols into your binary, and those collide if the same
//! binary also links a prebuilt `libssruntime`. The allocator and `panic-handler`
//! features are for the same builds, and are inert in an `rlib` that `std` backs.
//!
//! The allocator features are mutually exclusive — pairing `custom_alloc` with another
//! trips a `compile_error!` rather than the compiler's opaque "multiple global allocators".
//!
//! # `no_std`
//!
//! This crate is `no_std`-first and every release deliverable is built that way;
//! `std` exists for local developer convenience. An allocator is still required
//! (`alloc` is used for animation state and metadata), which is what the
//! `*_alloc` features above provide.
//!
//! A Rust dependent takes the crate as it comes:
//!
//! ```toml
//! ssruntime = "7.0.0-beta.1"
//! ```
//!
//! The binary deliverables are built from `ssruntime-ffi`, which passes these through:
//!
//! ```text
//! # Mobile / console / desktop, C-API
//! cargo build -p ssruntime-ffi --no-default-features --features ffi,libc_alloc,panic-handler
//! # Browser, wasm-bindgen
//! cargo build -p ssruntime-ffi --target wasm32-unknown-unknown --no-default-features --features web
//! # Pure WASM (WASI or a custom engine)
//! cargo build -p ssruntime-ffi --target wasm32-unknown-unknown --no-default-features --features ffi,wasm_alloc,panic-handler
//! ```
//!
//! # Limitations to design around
//!
//! - **Input is not validated.** To keep the binary small and playback allocation-free,
//!   `.ssab` is read zero-copy with no structural checks. Malformed or hostile input can
//!   cause out-of-bounds reads. Verifying asset integrity is the *Player's* job — do it
//!   before loading anything that came from a network or an end user. The FlatBuffers
//!   accessors do not bounds-check in release builds, so reading anything but a valid
//!   `.ssab` is undefined behaviour; that precondition is why [`AnimationResource::new`]
//!   and [`SsabResource::new`] are `unsafe fn`.
//! - **Borrowed buffers are not owned.** One [`AnimationResource`] may back several
//!   [`Context`]s, and across the C ABI resources are reference-counted — destroying a
//!   resource handle that contexts are still bound to is safe. What is *not* managed for
//!   you is the `.ssab` byte buffer behind `ss_resource_create_borrow`: it is never
//!   copied, so the caller must keep it alive and unmodified for as long as the resource
//!   exists. `ss_resource_create_copy` trades memory for not having to.
//!
